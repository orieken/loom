func TestSummaryCountsEveryActionAndCapsLongLists(t *testing.T) {
	change := Change{ID: "c1", RunID: "r1", Documented: 2}
	for i := 0; i < maxListed+4; i++ {
		change.Artifacts = append(change.Artifacts, Artifact{Target: "f" + string(rune('a'+i)), Kind: KindReadme, Action: ActionCreate})
	}
	change.Artifacts = append(change.Artifacts,
		Artifact{Target: "u", Action: ActionUpdate}, Artifact{Target: "k", Action: ActionUnchanged},
		Artifact{Target: "c", Action: ActionConflict, Reason: "edited"}, Artifact{Target: "s", Action: ActionSkip, Reason: "has docs"})
	change.Skipped = []SkippedCandidate{{Path: "d", Reason: "stale"}}
	summary := Summary(change)
	for _, want := range []string{"changeset c1 (from run r1): 2 directories documented", "19 to create, 1 to update, 1 unchanged, 1 conflicts, 1 skipped", "… and ", "CONFLICTS", "c  [, conflict] — edited", "Skipped (1)", "Verified results left out of this changeset (1)", "d — stale"} {
		if !strings.Contains(summary, want) {
			t.Errorf("summary lacks %q:\n%s", want, summary)
		}
	}
	if strings.Contains(summary, "Open questions") {
		t.Error("an empty section is omitted")
	}
	if got := Summary(Change{ID: "c2"}); !strings.Contains(got, "changeset c2 (no documenter run)") {
		t.Errorf("a codemap-only changeset has no run to cite: %s", got)
	}
}

func TestDigestIsStableAndPrefixed(t *testing.T) {
	a, again, b := Digest([]byte("a")), Digest([]byte("a")), Digest([]byte("b"))
	if a != again || a == b || !strings.HasPrefix(Digest(nil), "sha256:") {
		t.Error("digest")
	}
}

func TestDocumentBodySeparatesWhatWasWrittenFromWhatWasComputed(t *testing.T) {
	doc := state.RepoDocState{SchemaVersion: state.SchemaVersion, Path: "lib", InputHash: "h", Purpose: "Helpers.", Layer: state.LayerShared,
		Evidence: []state.DocEvidence{{Claim: "Helpers.", Fields: []string{"exports"}}}}
	sheet := factsheet.FactSheet{Path: "lib", Files: []string{"a.go", "b.go"}, Imports: []string{"x"}, ApproximateImports: []string{"legacy"},
		Dependents: []string{"app"}, Entrypoints: []string{"main.go"}, Tests: []string{"a_test.go"}}
	body, err := documentBody(doc, sheet)
	if err != nil {
		t.Fatal(err)
	}
	for _, want := range []string{"# lib", "Helpers.", "## Facts (computed from source)", "- Depends on: `x`", "- Possibly depends on (approximate): `legacy`", "- Used by: `app`", "- Entrypoints: `main.go`", "- Tests: `a_test.go`", "- Files: 2"} {
		if !strings.Contains(body, want) {
			t.Errorf("lacks %q:\n%s", want, body)
		}
	}
	if strings.Index(body, "Helpers.") > strings.Index(body, "## Facts") {
		t.Error("the written text comes before the computed facts")
	}
}

func TestEmptyFactsAreOmittedRatherThanListedAsNone(t *testing.T) {
	section := factsSection(factsheet.FactSheet{Path: "x"})
	if strings.Contains(section, "Depends on") || strings.Contains(section, "Used by") || !strings.Contains(section, "- Files: 0") {
		t.Errorf("%s", section)
	}
}


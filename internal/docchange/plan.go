// ErrNoRun is returned when there is no documenter run to plan from.
var ErrNoRun = errors.New("no documenter run found: run `loom document` first")

// legacyCodemapHeader marks a CODEMAP.md written by the retired shell script,
// which owned the whole file.
const legacyCodemapHeader = "Generated by `scripts/generate-codemap.sh`"

// PlanInput is everything Plan needs.
type PlanInput struct {
	Root       string
	RunID      string
	Options    Options
	Vocabulary repodoc.Vocabulary
	Lister     repograph.Lister
	Now        func() time.Time
}

// accepted is a verified candidate that is still true of the working tree.
type accepted struct {
	doc           state.RepoDocState
	sheet         factsheet.FactSheet
	sidecarDigest string
}

type planner struct {
	input    PlanInput
	change   Change
	sheets   []factsheet.FactSheet
	accepted []accepted
}

// Plan builds and stages a changeset from a run's verified candidates. It
// writes only under .loom/changes/<id>/: nothing in the repository, and
// nothing in the index, is touched until the changeset is approved and applied.
func Plan(input PlanInput) (Change, error) {
	p := &planner{input: input}
	if err := p.begin(); err != nil {
		return Change{}, err
	}
	p.acceptCandidates()
	if err := p.planDocuments(); err != nil {
		return Change{}, err
	}
	index, err := p.planIndex()
	if err != nil {
		return Change{}, err
	}
	if !input.Options.NoCodemap || input.Options.CodemapOnly {
		if err := p.planCodemap(index); err != nil {
			return Change{}, err
		}
	}
	return p.finish()
}

func (p *planner) begin() error {
	runs, err := p.runsToPlanFrom()
	if err != nil {
		return err
	}
	if len(runs) == 0 && !p.input.Options.CodemapOnly {
		return ErrNoRun
	}
	sheets, err := contextindex.CurrentSheets(p.input.Root, p.input.Lister)
	if err != nil {
		return err
	}
	p.sheets = sheets
	now := p.input.Now().UTC()
	p.change = Change{ID: p.freshID(now), Runs: runs, CreatedAt: now.Format(time.RFC3339),
		Options: p.input.Options, Artifacts: []Artifact{}, OpenQuestions: []OpenQuestion{}, Skipped: []SkippedCandidate{}}
	if len(runs) > 0 {
		p.change.RunID = runs[0]
	}
	return nil
}

// runsToPlanFrom is the named run, or every run, newest first: documenting in
// batches leaves one run per batch, and a changeset must not silently drop the
// earlier ones.
func (p *planner) runsToPlanFrom() ([]string, error) {
	if p.input.RunID != "" {
		return []string{p.input.RunID}, nil
	}
	return repodoc.Runs(p.input.Root)
}

// freshID is the timestamp id, suffixed when a changeset already holds it. Two
// plans in one second must not share a directory: the second would inherit the
// first's approval and applied record.
func (p *planner) freshID(now time.Time) string {
	base := now.Format("20060102T150405Z")
	id := base
	for attempt := 2; changeExists(p.input.Root, id); attempt++ {
		id = fmt.Sprintf("%s-%d", base, attempt)
	}
	return id
}

// acceptCandidates keeps the run's verified results that are still true. A
// result is re-verified here, against the tree as it is now: the tree may have
// changed since the run, and a file under .loom/runs is only a file.
func (p *planner) acceptCandidates() {
	byDir, err := p.candidatesByDirectory()
	if err != nil {
		p.skip(".", "could not read the run's candidates: "+err.Error())
		return
	}
	bySheet := map[string]factsheet.FactSheet{}
	for _, sheet := range p.sheets {
		bySheet[sheet.Path] = sheet
	}
	dirs := make([]string, 0, len(byDir))
	for dir := range byDir {
		dirs = append(dirs, dir)
	}
	sort.Strings(dirs)
	for _, dir := range dirs {
		if item, reason := p.firstValid(dir, byDir[dir], bySheet); item != nil {
			p.accepted = append(p.accepted, *item)
		} else {
			p.skip(dir, reason)
		}
	}
	p.change.Documented = len(p.accepted)
}

// candidatesByDirectory gathers each directory's candidate files across the
// runs, newest first.
func (p *planner) candidatesByDirectory() (map[string][]string, error) {
	byDir := map[string][]string{}
	for _, runID := range p.change.Runs {
		files, err := repodoc.Candidates(repodoc.RunDir(p.input.Root, runID))
		if err != nil {
			return nil, err
		}
		for dir, file := range files {
			byDir[dir] = append(byDir[dir], file)
		}
	}
	return byDir, nil
}

// firstValid takes the newest candidate that is still true of the tree. If none
// is, the reason given is the newest one's.
func (p *planner) firstValid(dir string, files []string, bySheet map[string]factsheet.FactSheet) (*accepted, string) {
	firstReason := ""
	for _, file := range files {
		item, reason := p.checkCandidate(dir, file, bySheet)
		if item != nil {
			return item, ""
		}
		if firstReason == "" {
			firstReason = reason
		}
	}
	return nil, firstReason
}

func (p *planner) checkCandidate(dir, file string, byPath map[string]factsheet.FactSheet) (*accepted, string) {
	raw, err := os.ReadFile(file)
	if err != nil {
		return nil, "unreadable: " + err.Error()
	}
	decoded, err := state.Decode(state.KindRepoDoc, raw)
	if err != nil {
		return nil, "invalid: " + err.Error()
	}
	doc := decoded.(*state.RepoDocState)
	sheet, exists := byPath[dir]
	if !exists {
		return nil, "the directory no longer exists"
	}
	if doc.InputHash != sheet.InputHash {
		return nil, "the directory changed since it was documented; run `loom document` again"
	}
	if violations := repodoc.Verify(sheet, *doc, p.input.Vocabulary); len(violations) > 0 {
		return nil, fmt.Sprintf("no longer verifies (%s)", violations[0].Code)
	}
	return &accepted{doc: *doc, sheet: sheet}, ""
}

func (p *planner) skip(dir, reason string) {
	p.change.Skipped = append(p.change.Skipped, SkippedCandidate{Path: dir, Reason: reason})
}

// planDocuments stages each accepted result's sidecar README, and the opt-in
// in-tree README and doc comments.
func (p *planner) planDocuments() error {
	for index := range p.accepted {
		item := &p.accepted[index]
		body, err := documentBody(item.doc, item.sheet)
		if err != nil {
			return err
		}
		if err := p.planSidecar(item, body); err != nil {
			return err
		}
		if err := p.planInTree(*item, body); err != nil {
			return err
		}
		p.collectQuestions(*item)
	}
	return nil
}

func (p *planner) planSidecar(item *accepted, body string) error {
	content := sidecarFile(body)
	item.sidecarDigest = Digest([]byte(content))
	return p.stageWhole(KindSidecarReadme, sidecarTarget(item.doc.Path), content)
}

func (p *planner) planInTree(item accepted, body string) error {
	if p.input.Options.InTreeReadmes {
		if err := p.stageBlock(KindReadme, readmeTarget(item.doc.Path), genblock.Markdown, body); err != nil {
			return err
		}
	}
	if !p.input.Options.DocComments {
		return nil
	}
	for _, edit := range commentEdits(p.input.Root, item.doc, item.sheet) {
		if err := p.stageEdit(KindDocComment, edit); err != nil {
			return err
		}
	}
	return nil
}

func (p *planner) collectQuestions(item accepted) {
	for _, question := range item.doc.OpenQuestions {
		p.change.OpenQuestions = append(p.change.OpenQuestions, OpenQuestion{Path: item.doc.Path, Question: question})
	}
}

// planIndex stages the index with every accepted directory recorded in it.
func (p *planner) planIndex() (contextindex.Index, error) {
	previous, _, err := contextindex.Load(p.input.Root)
	if err != nil {
		return contextindex.Index{}, err
	}
	if previous.Entries == nil {
		previous.Entries = map[string]contextindex.Entry{}
	}
	stamp := p.change.CreatedAt
	for _, item := range p.accepted {
		previous.Entries[item.doc.Path] = entryFor(item, stamp)
	}
	index := contextindex.Build(previous, p.sheets)
	if p.input.Options.CodemapOnly {
		return index, nil
	}
	raw, err := contextindex.Marshal(index)
	if err != nil {
		return index, err
	}
	return index, p.stageWhole(KindIndex, repograph.OutputDir+"/"+contextindex.File, string(raw))
}

func entryFor(item accepted, stamp string) contextindex.Entry {
	tags := item.doc.Tags
	if tags == nil {
		tags = []string{}
	}
	questions := item.doc.OpenQuestions
	if questions == nil {
		questions = []string{}
	}
	return contextindex.Entry{Purpose: item.doc.Purpose, Tags: tags, Layer: string(item.doc.Layer), InputHash: item.doc.InputHash,
		DocHash: item.sidecarDigest, GeneratedAt: stamp, OpenQuestions: questions}
}

// planCodemap stages CODEMAP.md. A file the retired script wrote is wholly
// generated, so it is replaced; anything else keeps its human text and only
// the marked block is managed.
func (p *planner) planCodemap(index contextindex.Index) error {
	body := codemapBody(p.sheets, index)
	current, exists, err := readTarget(p.input.Root, "CODEMAP.md")
	if err != nil {
		return err
	}
	if exists && strings.Contains(current, legacyCodemapHeader) && !strings.Contains(current, "loom:generated:start") {
		return p.stageWhole(KindCodemap, "CODEMAP.md", genblock.Markdown.Render(body)+"\n")
	}
	return p.stageBlock(KindCodemap, "CODEMAP.md", genblock.Markdown, body)
}

func (p *planner) finish() (Change, error) {
	sort.SliceStable(p.change.Artifacts, func(i, j int) bool { return p.change.Artifacts[i].Target < p.change.Artifacts[j].Target })
	if err := Save(p.input.Root, p.change); err != nil {
		return Change{}, err
	}
	return p.change, nil
}

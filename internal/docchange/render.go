package docchange

import (
	"encoding/json"
	"fmt"
	"strings"

	"github.com/orieken/loom/internal/factsheet"
	"github.com/orieken/loom/internal/state"
)

// documentBody renders a verified result as markdown, then appends the facts
// that were computed rather than written: what the directory depends on and
// what depends on it. The model's text and the extractor's facts are visibly
// separate, so a reader can tell interpretation from record.
func documentBody(doc state.RepoDocState, sheet factsheet.FactSheet) (string, error) {
	raw, err := json.Marshal(doc)
	if err != nil {
		return "", fmt.Errorf("encode document %s: %w", doc.Path, err)
	}
	_, view, err := state.RenderView(state.KindRepoDoc, raw)
	if err != nil {
		return "", err
	}
	return strings.TrimRight(view, "\n") + "\n\n" + factsSection(sheet), nil
}

// factsSection lists computed facts. An approximate edge is labelled as one.
func factsSection(sheet factsheet.FactSheet) string {
	var out strings.Builder
	out.WriteString("## Facts (computed from source)\n\n")
	writeFact(&out, "Depends on", sheet.Imports)
	writeFact(&out, "Possibly depends on (approximate)", sheet.ApproximateImports)
	writeFact(&out, "Used by", sheet.Dependents)
	writeFact(&out, "Possibly used by (approximate)", sheet.ApproximateDependents)
	writeFact(&out, "Entrypoints", sheet.Entrypoints)
	writeFact(&out, "Tests", sheet.Tests)
	fmt.Fprintf(&out, "- Files: %d\n", len(sheet.Files))
	return out.String()
}

func writeFact(out *strings.Builder, label string, values []string) {
	if len(values) == 0 {
		return
	}
	quoted := make([]string, 0, len(values))
	for _, value := range values {
		quoted = append(quoted, "`"+value+"`")
	}
	fmt.Fprintf(out, "- %s: %s\n", label, strings.Join(quoted, ", "))
}

// sidecarFile is a sidecar document: generated whole, so it carries a header
// saying so instead of markers.
func sidecarFile(body string) string {
	return "<!-- Generated by loom from a verified repo-documenter result. Do not edit: regenerated by `loom docs`. -->\n\n" + body
}

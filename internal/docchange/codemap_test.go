func codemapFixture() ([]factsheet.FactSheet, contextindex.Index) {
	sheets := []factsheet.FactSheet{
		{Path: ".", Children: []string{"cmd", "lib"}},
		{Path: "cmd", Children: []string{"cmd/app"}},
		{Path: "cmd/app", Entrypoints: []string{"main.go"}, Imports: []string{"lib"}},
		{Path: "lib", Dependents: []string{"cmd/app", "svc"}},
		{Path: "svc", Imports: []string{"lib"}},
		{Path: "deep/er/down", Files: []string{"x.go"}},
	}
	index := contextindex.Index{Entries: map[string]contextindex.Entry{
		"lib": {Purpose: "shared helpers | with a pipe", Layer: "shared"}, "cmd/app": {Purpose: "the program", Layer: "framework"},
	}}
	return sheets, index
}

func TestCodemapListsEntrypointsFanInLayersAndPurposes(t *testing.T) {
	sheets, index := codemapFixture()
	body := codemapBody(sheets, index)
	for _, want := range []string{
		"## Entrypoints\n\n- `cmd/app/main.go`",
		"- `lib` — 2 dependents — shared helpers | with a pipe",
		"- **framework**: `cmd/app`", "- **shared**: `lib`",
		"| `lib/` | shared helpers \\| with a pipe |", "| `cmd/app/` | the program |",
	} {
		if !strings.Contains(body, want) {
			t.Errorf("CODEMAP lacks %q:\n%s", want, body)
		}
	}
}

func TestCodemapNeverCarriesAPlaceholder(t *testing.T) {
	sheets, index := codemapFixture()
	body := codemapBody(sheets, index)
	if strings.Contains(body, "TODO") {
		t.Errorf("an indexed directory with no purpose is undocumented, not a TODO:\n%s", body)
	}
	if !strings.Contains(body, "| `svc/` | _undocumented_ |") {
		t.Errorf("%s", body)
	}
	if strings.Contains(body, "deep/er/down") {
		t.Error("the directory table stops at depth 2")
	}
}


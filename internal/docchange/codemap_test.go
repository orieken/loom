func TestCodemapRanksFanInByCountThenPathAndCapsTheList(t *testing.T) {
	var sheets []factsheet.FactSheet
	for i := 0; i < maxFanIn+3; i++ {
		deps := make([]string, i%4+1)
		sheets = append(sheets, factsheet.FactSheet{Path: "d" + string(rune('a'+i)), Dependents: deps})
	}
	body := codemapBody(sheets, contextindex.Index{})
	if got := strings.Count(body, " dependents — "); got != maxFanIn {
		t.Errorf("the fan-in list is capped at %d, got %d", maxFanIn, got)
	}
	first := strings.Index(body, "4 dependents")
	last := strings.Index(body, "1 dependents")
	if first < 0 || last < 0 || first > last {
		t.Errorf("highest first:\n%s", body)
	}
}

func TestCodemapCapsTheEntrypointList(t *testing.T) {
	var sheets []factsheet.FactSheet
	for i := 0; i < maxEntrypoints+5; i++ {
		sheets = append(sheets, factsheet.FactSheet{Path: "d" + string(rune('a'+i%26)) + string(rune('a'+i/26)), Entrypoints: []string{"main.go"}})
	}
	if body := codemapBody(sheets, contextindex.Index{}); !strings.Contains(body, "- … and 5 more") {
		t.Errorf("%s", body)
	}
}

func TestCodemapIsDeterministic(t *testing.T) {
	sheets, index := codemapFixture()
	first, second := codemapBody(sheets, index), codemapBody(sheets, index)
	if first != second {
		t.Error("the same inputs must give the same text")
	}
}

func TestACodemapWrittenByTheRetiredScriptIsReplacedWholesale(t *testing.T) {
	root := newRepo(t, map[string]string{
		"go.mod": goRepo["go.mod"], "lib/lib.go": goRepo["lib/lib.go"],
		"CODEMAP.md": "# CODEMAP\n\nGenerated by `scripts/generate-codemap.sh` — regenerate.\n\n### `x/`\n\nTODO — add README.md\n",
	})
	documentedRun(t, root, nil)
	approveAndApply(t, root, plan(t, root, Options{}).ID)
	got := readFile(t, root, "CODEMAP.md")
	if strings.Contains(got, "TODO") || strings.Contains(got, "generate-codemap.sh") || !strings.Contains(got, "loom:generated:start") {
		t.Errorf("the legacy file is wholly generated and is replaced:\n%s", got)
	}
}

func TestACodemapWithHumanTextKeepsItAndOnlyTheBlockIsManaged(t *testing.T) {
	root := newRepo(t, map[string]string{
		"go.mod": goRepo["go.mod"], "lib/lib.go": goRepo["lib/lib.go"], "CODEMAP.md": "# Our map\n\nWritten by hand.\n",
	})
	documentedRun(t, root, nil)
	approveAndApply(t, root, plan(t, root, Options{}).ID)
	got := readFile(t, root, "CODEMAP.md")
	if !strings.HasPrefix(got, "# Our map\n\nWritten by hand.\n") || !strings.Contains(got, "## Entrypoints") {
		t.Errorf("%s", got)
	}
}

func TestNoCodemapLeavesItOutOfTheChangeset(t *testing.T) {
	root := newRepo(t, goRepo)
	documentedRun(t, root, nil)
	for _, artifact := range plan(t, root, Options{NoCodemap: true}).Artifacts {
		if artifact.Kind == KindCodemap {
			t.Errorf("--no-codemap was ignored: %+v", artifact)
		}
	}
}

func TestCodemapOnlyStagesNothingButCodemapAndNeedsNoRun(t *testing.T) {
	root := newRepo(t, goRepo)
	change := plan(t, root, Options{CodemapOnly: true})
	if len(change.Artifacts) != 1 || change.Artifacts[0].Target != "CODEMAP.md" || change.Artifacts[0].Action != ActionCreate {
		t.Errorf("artifacts = %+v", change.Artifacts)
	}
}

func TestCodemapOnlyGivesAnIndexedOnlyRepoARealMapWithoutTouchingTheIndex(t *testing.T) {
	root := newRepo(t, goRepo)
	approveAndApply(t, root, plan(t, root, Options{CodemapOnly: true}).ID)
	got := readFile(t, root, "CODEMAP.md")
	if !strings.Contains(got, "`cmd/app/main.go`") || !strings.Contains(got, "_undocumented_") || strings.Contains(got, "TODO") {
		t.Errorf("%s", got)
	}
	if exists(root, ".loom/index.json") {
		t.Error("--codemap-only must not touch the index")
	}
}

